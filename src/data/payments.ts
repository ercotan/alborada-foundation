/**
 * The only origin this integration is allowed to load a script from.
 * Asserted by `payments.test.ts`, so a typo or a substituted host fails the
 * suite rather than shipping.
 */
export const PAYPAL_SDK_ORIGIN = "https://www.paypal.com";

/** Query parameters exactly as the PayPal button builder produced them. */
export const PAYPAL_SDK_PARAMS = {
  "client-id": PAYPAL_CLIENT_ID,
  components: "hosted-buttons",
  "disable-funding": "venmo",
  currency: "USD",
} as const;

/**
 * Builds the SDK URL from the parts above.
 *
 * Built rather than pasted so the identifiers exist once. `URL` also
 * guarantees the result is a well-formed absolute HTTPS URL, which a
 * hand-concatenated string does not.
 */
export function paypalSdkUrl(): string {
  const url = new URL("/sdk/js", PAYPAL_SDK_ORIGIN);
  for (const [key, value] of Object.entries(PAYPAL_SDK_PARAMS)) {
    url.searchParams.set(key, value);
  }
  return url.toString();
}

export const PAYPAL_SDK_URL = paypalSdkUrl();

/**
 * Public PayPal configuration for the online donation.
 *
 * ---------------------------------------------------------------------------
 * WHAT IS IN THIS FILE
 * ---------------------------------------------------------------------------
 * These are **public PayPal hosted-button identifiers**. A hosted-button id, a
 * hosted-button client id and a PayPal.me-style payment link are all designed
 * to be readable by every visitor — they are embedded in the page the browser
 * downloads, and they cannot be otherwise.
 *
 * **No private API secret is present, and none may ever be added here.** A
 * PayPal REST secret, an access token or a webhook signing key would be
 * inlined into the bundle by Vite and published to the world. If server-side
 * PayPal work is ever needed, it belongs on a server, behind a variable
 * without the `VITE_` prefix — see `.env.example`.
 *
 * ---------------------------------------------------------------------------
 * WHO RECEIVES THE MONEY
 * ---------------------------------------------------------------------------
 * **Fundación Unidos por un Acuerdo Social — FUNUDOS** receives the donation.
 * **Fundación Alborada** is the public project that FUNUDOS administers. The
 * donation section states this to the visitor; it is not left implicit.
 *
 * ---------------------------------------------------------------------------
 * WHAT THIS SITE DOES NOT DO
 * ---------------------------------------------------------------------------
 * PayPal hosts and processes the payment in full. This site does not collect
 * card details or PayPal credentials, does not create orders, does not store
 * payment information, and never displays a success state of its own — only
 * PayPal can tell a donor that a payment completed.
 *
 * Values here were generated by the PayPal hosted-button builder for the
 * foundation's own account. Do not change them without saying so explicitly.
 */

